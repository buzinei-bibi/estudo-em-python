1.	# o menor valor (min)
2.	# o maior valor (max)
3.	# a soma de todos os valores (sum)
4.	# a média usando sum e len

numeros = [7,14,21,28,35,42,49] 

print("menor valor :" , min (numeros))
print (" maior valor:", max (numeros))

print ("a soma de todos os valores: " , sum (numeros))
print ("a média: " , sum (numeros) / len (numeros)) 